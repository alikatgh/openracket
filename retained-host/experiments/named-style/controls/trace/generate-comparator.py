def verify_sources():
    for name, expected in SOURCE_PINS.items():
        actual = hashlib.sha256((HERE / name).read_bytes()).hexdigest()
        if actual != expected:
            raise ValueError(f"proven source changed: {name}: {actual}")


def replace_once(source, old, new):
    if source.count(old) != 1:
        raise ValueError(f"expected one unchanged source anchor: {old!r}")
    return source.replace(old, new, 1)


def generated_source():
    verify_sources()
    source = (HERE / "upstream/tests/compare-trace.py").read_text(encoding="utf-8")
    tree = ast.parse(source)
    functions = {node.name: ast.get_source_segment(source, node)
                 for node in tree.body if isinstance(node, ast.FunctionDef)}
    compare = functions["compare"]
    # Only validation context, arm labels and reporting change. The full loop,
    # semantic projection, diagnostics and acceptance comparison are preserved.
    compare = replace_once(compare,
        '    captures = [("stock", stock), ("stock-again", stock_again), ("off", off), ("on", on)]',
        '    require(manifest.get("original_sha256") == "' + XREF_ORIGINAL_SHA256 + '",\n'
        '            "expected the pinned unchanged xref manifest, not the binding GUI manifest")\n'
        '    captures = [("stock", stock), ("stock-again", stock_again),\n'
        '                ("binding-candidate-off", off), ("binding-candidate-on", on)]')
    compare = replace_once(compare,
        'strict.validate(capture, "stock" if label.startswith("stock") else label, manifest)',
        'strict.validate(capture, "stock", manifest)')
    compare = replace_once(compare,
        '            "actual_enabled_activation": True,',
        '            "xref_capture_mode": "stock",\n'
        '            "external_capture_labels": [label for label, _ in captures],\n'
        '            "binding_gui_activation": "not_assessed_by_this_worker_trace_gate",')
    compare = replace_once(compare,
        '"Completed annotation, binding/navigation and five-query rename contract only; transient GUI replay/paint ordering and timing remain unproven."',
        '"Completed worker annotation, projected binding/navigation and five-query rename contract only. External arm labels are caller-supplied; binding GUI activation, actual GUI graph/navigation, transient replay/paint ordering and timing require separate evidence."')
    main = functions["main"]
    # The positional call remains unchanged; these names describe outer arms,
    # never the raw capture's xref mode.
    cli_names = '("stock", "stock_again", "off", "on")'
    if main.count(cli_names) != 2:
        raise ValueError("expected exactly two unchanged CLI argument-name lists")
    main = main.replace(cli_names, '("stock", "stock_again", "binding_off", "binding_on")')
    main = replace_once(main, '(HERE.parent / "manifest.json")',
                        '(HERE / "upstream/manifest.json")')
    return HEADER + compare + "\n\n\n" + main + '\n\n\nif __name__ == "__main__":\n    sys.exit(main())\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args()
    expected = generated_source().encode("utf-8")
    target = HERE / "compare-binding-trace.py"
    if args.check:
        if target.read_bytes() != expected:
            raise SystemExit("FAIL: generated comparator differs; inspect before regenerating")
        print("PASS: seven upstream SHA256 pins and exact generated wrapper")
    else:
        target.write_bytes(expected)
        print(target)


if __name__ == "__main__":
    main()
